async def main() -> int:
    key = os.environ.get("AI_CHAT_WEATHER_KEY", "")
    host = os.environ.get("AI_CHAT_WEATHER_HOST", "")
    if not key or not host:
        print("缺少 AI_CHAT_WEATHER_KEY / AI_CHAT_WEATHER_HOST（进程环境注入）", file=sys.stderr)
        return 2
    ok: dict[str, str] = {}
    fail: list[str] = []
    async with httpx.AsyncClient(timeout=15.0) as client:
        for name, coord in CANDIDATES.items():
            try:
                r = await client.get(
                    f"https://{host}/v7/weather/now?location={coord}",
                    headers={"X-QW-Api-Key": key},
                )
                d = r.json() if r.status_code == 200 else {}
                now = d.get("now", {})
                slug = (d.get("fxLink") or "").rsplit("/", 1)[-1].removesuffix(".html")
                r3 = await client.get(
                    f"https://{host}/v7/weather/3d?location={coord}",
                    headers={"X-QW-Api-Key": key},
                )
                d3 = r3.json() if r3.status_code == 200 else {}
                days = len(d3.get("daily", []))
                if r.status_code == 200 and days == 3:
                    ok[name] = coord
                    print(f"OK   {name:<6} {coord:<12} now={now.get('text')} {now.get('temp')}°C  3d={days}  slug={slug}")
                else:
                    fail.append(name)
                    print(f"FAIL {name:<6} {coord:<12} now_code={r.status_code} 3d_code={r3.status_code} days={days}")
            except Exception as exc:  # noqa: BLE001 —— 报告用，逐城继续
                fail.append(name)
                print(f"FAIL {name:<6} {coord:<12} {type(exc).__name__}: {exc}")
    print(f"\n=== 通过 {len(ok)} / 候选 {len(CANDIDATES)}；失败 {len(fail)}: {fail} ===\n")
    print("CITY_TABLE = {")
    for name, coord in ok.items():
        print(f'    "{name}": "{coord}",')
    print("}")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
